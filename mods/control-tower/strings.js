/** The languages in the order the language button steps through them.
 *  `label` is what the button shows; `name` is the language's own name. */
export const LANGS = [
  { id: "en", label: "EN", name: "English" },
  { id: "ko", label: "한", name: "한국어" },
  { id: "ja", label: "日", name: "日本語" },
  { id: "zh", label: "中", name: "简体中文" },
  { id: "es", label: "ES", name: "Español" },
  { id: "de", label: "DE", name: "Deutsch" },
  { id: "fr", label: "FR", name: "Français" },
  { id: "pt", label: "PT", name: "Português" },
];

export const hasLang = (id) => typeof id === "string" && LANGS.some((l) => l.id === id);

/** The language for a system locale ("ko-KR", "pt_BR", "zh-Hant-TW"): its first
 *  part when there is a table for it, else English. */
export function pickLang(locale) {
  const first = String(locale ?? "").toLowerCase().split(/[-_.@]/)[0];
  return hasLang(first) ? first : "en";
}

/** The language after `id` on the button; from the last (or an unknown one) back to the first. */
export function nextLang(id) {
  const i = LANGS.findIndex((l) => l.id === id);
  return LANGS[(i + 1) % LANGS.length].id;
}

export const langLabel = (id) => LANGS.find((l) => l.id === id)?.label ?? "EN";
export const langName = (id) => LANGS.find((l) => l.id === id)?.name ?? "English";
